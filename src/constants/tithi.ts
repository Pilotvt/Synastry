function rewriteTithiDescriptionForDay(description: string, targetDay: number): string {
  if (!description) return description;
  const safe = Math.max(1, Math.min(30, Math.round(targetDay)));
  let next = description.replace(/^\s*\d+\s*[-]?\s*(?:е|ые)\s+лунные\s+сутки/iu, `${safe}е лунные сутки`);

  // Special case: for 26-е сутки (Кришна Экадаши) adjust the embedded example that references 11/12.
  if (safe === 26) {
    const dayLabel = `${safe}е лунные сутки`;
    const nextDayLabel = `${safe + 1}е лунные сутки`;
    next = next
      .replace(/\b11\s*(?:е|ые)\s+лунные\s+сутки\b/giu, dayLabel)
      .replace(/\b12\s*(?:е|ые)\s+лунные\s+сутки\b/giu, nextDayLabel);
  }

  return next;
}

const TITHI_STATIC_1_30: Record<number, TithiStatic> = (() => {
  const result: Record<number, TithiStatic> = {};
  for (let day = 1; day <= 30; day += 1) {
    if (day === 30) {
      result[day] = TITHI_30;
      continue;
    }
    const baseDay = day > 15 ? day - 15 : day;
    const base = TITHI_STATIC_1_15[baseDay] ?? { title: "", description: "" };
    result[day] = {
      title: base.title,
      description: day > 15 ? rewriteTithiDescriptionForDay(base.description, day) : base.description,
    };
  }
  return result;
})();

export function tithiOrdinalRu(tithi: number): string {
  if (!Number.isFinite(tithi)) return "";
  const safe = Math.max(1, Math.min(30, Math.round(tithi)));
  return `${safe}-\u0435`;
}

export function tithiPakshaRu(paksha: TithiPaksha): string {
  return paksha === "krishna" ? "Кришна" : "Шукла";
}

export function getTithiStatic(tithi: number): TithiStatic {
  const safe = Math.max(1, Math.min(30, Math.round(tithi)));
  return TITHI_STATIC_1_30[safe] ?? { title: "", description: "" };
}
